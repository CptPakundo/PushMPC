// PushMPC for IINA: the best picture IINA's own player can give without a VapourSynth-enabled libmpv.
//  - Upscaling: GLSL user shaders through mpv's glsl-shaders (IINA renders through OpenGL 4.1, so fragment and
//    textureGather shaders only). Auto picks by chip: base M1 / M2 -> FSR 1, base M3+ -> RAVU-Lite r3,
//    Pro -> FSRCNNX 8 (anime: RAVU-Lite r4), Max / Ultra and M4+ Pro -> FSRCNNX 16 (anime: RAVU-Lite r4). Each shader
//    only runs when the video is drawn larger than its size (the shaders' own WHEN conditions).
//  - Smooth motion: video-sync=display-resample + interpolation with tscale=oversample (each video frame shown for
//    its exact share of display refreshes, blending only at the boundaries: no judder, no soap-opera look). That is
//    not frame generation: real interpolated frames need the PushMPC filter in mpv (Homebrew mpv + `brew install
//    pushmpc`), which IINA's libmpv cannot load.
//  - HDR: untouched (IINA's own EDR / tone mapping stays in charge).
//  - Frame generation: when Homebrew's pushmpc installed the bridge (pushmpc-iina.so), it is loaded into IINA's libmpv
//    and the marked filter vf=@pushmpc:lavfi=[null@pushmpc] runs PushMPC's apple engine (VideoToolbox interpolation,
//    super resolution, ArtCNN on Metal) zero copy on IINA's VideoToolbox frames. IINA.app is not modified.
// Shaders are bundled in shaders.js (generated by build.py from shaders.lock.json) and written once to the plugin's
// data folder, because mpv needs real files.
const { core, mpv, event, menu, preferences, utils, file, console } = iina;

let BUNDLE = { version: "dev", files: {}, presets: {} };
try {
  BUNDLE = require("./shaders.js") || BUNDLE;
} catch (e) {
  console.log("PushMPC: shaders.js missing (an unbuilt plugin folder): upscaling off. " + e);
}

const QUALITIES = ["auto", "off", "light", "balanced", "high", "ultra"];
const LABELS = { auto: "Auto (by chip)", off: "Off", light: "Light: FSR 1", balanced: "Balanced: RAVU-Lite r3", high: "High: FSRCNNX 8 / ArtCNN C4F16", ultra: "Ultra: FSRCNNX 16 / ArtCNN C4F32" };

// The PushMPC bridge (Homebrew pushmpc installs it): an mpv C plugin that runs PushMPC's engine inside IINA's libmpv
// (src/iina_bridge.mm). Loaded once per player with load-script; it reports back through user-data/pushmpc/bridge.
const BRIDGE_PATHS = ["/opt/homebrew/lib/pushmpc/pushmpc-iina.so", "/usr/local/lib/pushmpc/pushmpc-iina.so"];
let bridgeState = "unknown";   // unknown | missing | loaded | active | off: <why>
async function bridge() {
  if (bridgeState !== "unknown" && bridgeState !== "loaded") return bridgeState;
  if (bridgeState === "unknown") {
    let path = "";
    for (const p of BRIDGE_PATHS) {
      try { const r = await utils.exec("/bin/test", ["-f", p]); if (r && r.status === 0) { path = p; break; } } catch (e) { /* not there */ }
    }
    if (!path) { bridgeState = "missing"; return bridgeState; }
    mpv.command("load-script", [path]);
    bridgeState = "loaded";
  }
  const s = (mpv.getString("user-data/pushmpc/bridge") || "").replace(/^"|"$/g, "");   // user-data comes back JSON-quoted
  if (s) bridgeState = s;
  return bridgeState;
}

function pref(key, def) {
  const v = preferences.get(key);
  return v === undefined || v === null || v === "" ? def : v;
}

// "Apple M2 Pro" -> { gen: 2, tier: "pro" }
let chipCache = null;
async function chip() {
  if (chipCache) return chipCache;
  chipCache = { name: "unknown", gen: 0, tier: "base" };
  try {
    const r = await utils.exec("/usr/sbin/sysctl", ["-n", "machdep.cpu.brand_string"]);
    const name = (r && r.stdout ? r.stdout : "").trim();
    const m = /Apple M(\d+)(?:\s+(Pro|Max|Ultra))?/i.exec(name);
    chipCache = { name: name || "unknown", gen: m ? parseInt(m[1], 10) : 0, tier: m && m[2] ? m[2].toLowerCase() : (m ? "base" : "intel") };
  } catch (e) {
    console.log("PushMPC: chip detection failed: " + e);
  }
  return chipCache;
}

function autoQuality(c) {
  if (c.tier === "max" || c.tier === "ultra") return "ultra";
  if (c.tier === "pro") return c.gen >= 4 ? "ultra" : "high";
  if (c.tier === "intel") return "light";
  return c.gen >= 3 ? "balanced" : "light";
}

// write the bundled shaders to @data/shaders once per bundle version; returns { name: absolute path }
function ensureShaders() {
  const paths = {};
  const names = Object.keys(BUNDLE.files || {});
  if (!names.length) return paths;
  const marker = "@data/shaders/.bundle-version";
  let current = "";
  try { if (file.exists(marker)) current = file.read(marker); } catch (e) { current = ""; }
  for (const n of names) {
    const p = "@data/shaders/" + n;
    if (current !== BUNDLE.version || !file.exists(p)) file.write(p, BUNDLE.files[n]);
    paths[n] = utils.resolvePath(p);
  }
  if (current !== BUNDLE.version) file.write(marker, BUNDLE.version);
  return paths;
}

let lastApplied = "";
async function apply(reason) {
  const quality = pref("quality", "auto");
  // Content Auto: what PushMPC's bridge measures in the picture (user-data/pushmpc/content), never the file name;
  // live action until it has measured drawn animation
  const contentPref = pref("content", "auto");
  const measured = (mpv.getString("user-data/pushmpc/content") || "").replace(/^"|"$/g, "");
  const content = contentPref === "auto" ? (measured === "anime" ? "anime" : "live") : contentPref;
  const motion = pref("motion", true) !== false && pref("motion", true) !== "false";
  const tscale = pref("tscale", "oversample");
  const framegen = pref("framegen", true) !== false && pref("framegen", true) !== "false";
  const b = framegen ? await bridge() : "disabled";
  const fg = b === "active" || b === "loaded";
  // the bridge's marked no-op graph: PushMPC's engine takes its frames (any other vf stays as it is)
  mpv.command("vf", ["remove", "@pushmpc"]);
  if (fg) mpv.command("vf", ["add", "@pushmpc:lavfi=[null@pushmpc]"]);
  const c = await chip();
  const q = quality === "auto" ? autoQuality(c) : quality;
  const preset = (BUNDLE.presets || {})[q];
  const names = q === "off" || !preset ? [] : (preset[content] || preset.live || []);
  let paths = {};
  try { paths = ensureShaders(); } catch (e) { console.log("PushMPC: could not write the shaders: " + e); }
  const list = names.filter((n) => paths[n]).map((n) => paths[n]);

  mpv.command("change-list", ["glsl-shaders", "clr", ""]);
  for (const p of list) mpv.command("change-list", ["glsl-shaders", "append", p]);
  if (fg) {
    mpv.set("interpolation", false);   // real generated frames: mpv's blending would fight them
  } else if (motion) {
    mpv.set("video-sync", "display-resample");
    mpv.set("interpolation", true);
    mpv.set("tscale", tscale);
  } else {
    mpv.set("interpolation", false);
  }
  const summary = (fg ? "PushMPC frame generation, " : "") + (names.length ? names.join(" + ") : "no upscaling shader") + (!fg && motion ? ", smooth motion (" + tscale + ")" : "") +
    (framegen && b === "missing" ? " (bridge not installed: brew install pushmpc)" : "") + (framegen && b.startsWith("off") ? " (bridge " + b + ")" : "");
  const key = summary + "|" + c.name;
  if (key !== lastApplied) {
    lastApplied = key;
    console.log("PushMPC (" + reason + "): " + c.name + ", quality " + quality + (quality === "auto" ? " -> " + q : "") + ", " + content + ": " + summary);
    if (reason !== "start") core.osd("PushMPC: " + summary);
  }
}

function buildMenu() {
  menu.removeAllItems();
  const root = menu.item("PushMPC");
  const quality = pref("quality", "auto");
  for (const q of QUALITIES) {
    root.addSubMenuItem(menu.item(LABELS[q], () => { preferences.set("quality", q); buildMenu(); apply("menu"); }, { selected: q === quality }));
  }
  const content = pref("content", "auto");
  root.addSubMenuItem(menu.item("Content: Auto (measured)", () => { preferences.set("content", "auto"); buildMenu(); apply("menu"); }, { selected: content === "auto" }));
  root.addSubMenuItem(menu.item("Content: live action", () => { preferences.set("content", "live"); buildMenu(); apply("menu"); }, { selected: content === "live" }));
  root.addSubMenuItem(menu.item("Content: anime", () => { preferences.set("content", "anime"); buildMenu(); apply("menu"); }, { selected: content === "anime" }));
  const framegen = pref("framegen", true) !== false && pref("framegen", true) !== "false";
  root.addSubMenuItem(menu.item("Frame generation (PushMPC bridge)", () => { preferences.set("framegen", !framegen); buildMenu(); apply("menu"); }, { selected: framegen }));
  const motion = pref("motion", true) !== false && pref("motion", true) !== "false";
  root.addSubMenuItem(menu.item("Smooth motion (display-resample)", () => { preferences.set("motion", !motion); buildMenu(); apply("menu"); }, { selected: motion }));
  menu.addItem(root);
  menu.forceUpdate();
}

event.on("iina.window-loaded", () => { buildMenu(); });
event.on("iina.file-loaded", () => { apply("file"); });
// the measured content changed (the bridge publishes it at most every 0.5 s; its class changes at most once per shot)
let lastMeasured = "";
const onMeasured = () => {
  if (pref("content", "auto") !== "auto") return;
  const m = (mpv.getString("user-data/pushmpc/content") || "").replace(/^"|"$/g, "");
  if (m && m !== lastMeasured) { lastMeasured = m; apply("measured " + m); }
};
if (typeof setInterval === "function") setInterval(onMeasured, 2000);
else event.on("mpv.user-data/pushmpc/content.changed", onMeasured);
apply("start");
