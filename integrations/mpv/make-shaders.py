#!/usr/bin/env python3
"""Generates the upscaling shader set pushmpc.lua falls back to (Plex, GPUs without PushMPC's own upscaler, libmpv
hosts): ArtCNN C4F16 and C4F32 luma doublers as mpv FRAGMENT passes (OpenGL, D3D11 and Vulkan renderers alike), made by
vsplugin/tools/artcnn_tool.py from the ONNX weights pinned in vsplugin/models/artcnn.lock.json (the same generator and
pins as the IINA plugin; nothing is copied). Standard library only.

  make-shaders.py OUT_DIR [--cache DIR]

OUT_DIR gets ArtCNN_C4F16_fragment.glsl, ArtCNN_C4F32_fragment.glsl and SHADER-LICENSES.txt. Exit code 0 = done."""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(os.path.dirname(os.path.dirname(HERE)), "vsplugin", "tools")
sys.path.insert(0, TOOLS)
import artcnn_tool  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--cache", default="")
a = ap.parse_args()
cache = a.cache or os.path.join(a.out, ".onnx-cache")
os.makedirs(a.out, exist_ok=True)
artcnn_tool.fetch(artcnn_tool.DEFAULT_LOCK, cache, ["ArtCNN_C4F16.onnx", "ArtCNN_C4F32.onnx"])
lock = json.load(open(artcnn_tool.DEFAULT_LOCK, encoding="utf-8"))
lines = []
for m in ("C4F16", "C4F32"):
    name = f"ArtCNN_{m}_fragment.glsl"
    n = artcnn_tool.write_glsl(artcnn_tool.layers_from_onnx(os.path.join(cache, f"ArtCNN_{m}.onnx")), os.path.join(a.out, name), f"ArtCNN {m}")
    text = open(os.path.join(a.out, name), encoding="utf-8").read()
    if "//!COMPUTE" in text or "//!WHEN" not in text:
        raise SystemExit(f"{name}: expected fragment passes with a //!WHEN guard")
    lines.append(f"{name}: ArtCNN {m} luma doubler, {n} fragment passes, generated by PushMPC's vsplugin/tools/artcnn_tool.py "
                 f"from the upstream ONNX weights at commit {lock['commit']}. Licence: MIT ({lock['copyright']}). "
                 f"Source: {lock['repository']}. The licence text is in the file's header.")
    print(f"{name}: {n} passes")
open(os.path.join(a.out, "SHADER-LICENSES.txt"), "w", newline="\n").write("\n".join(lines) + "\n")
if not a.cache:
    import shutil
    shutil.rmtree(cache, ignore_errors=True)
