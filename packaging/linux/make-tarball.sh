#!/bin/sh
# Builds the Linux release tarball pushmpc-linux-<arch>-<version>.tar.gz (user-level install, no root):
#   pushmpc-linux-<arch>-<version>/
#     setup.sh                   integrations/linux/setup.sh (the one command: every player, engine plan, uninstall)
#     install.sh                 integrations/linux/install.sh (install | uninstall | status)
#     mpv-integration.sh         integrations/mpv/mpv-integration.sh (the mpv.conf block)
#     vsplugin/pushmpc_vs.so     the VapourSynth plugin (portable backend)
#     vsplugin/pushmpc.vpy       the script mpv runs (vsplugin/scripts/pushmpc.vpy)
#     vsplugin/pushmpc.lua       adds the filter at run time (integrations/mpv/pushmpc.lua)
#     vsplugin/shaders/          ArtCNN C4F16 / C4F32 fragment shaders (integrations/mpv/make-shaders.py)
#     capture/                   capture mode: pushmpc-capture and pushmpc-capture.sh (PUSHMPC_CAPTURE_BIN, optional)
#     LICENSE, README.txt
#   make-tarball.sh <pushmpc_vs.so> <out dir> <arch> <version> [<pushmpc-nvvfx-selftest>]   (run from the repository root)
set -eu
so=$1; arch=$3; ver=$4
mkdir -p "$2"; out=$(cd "$2" && pwd)
name=pushmpc-linux-$arch-$ver
tmp=$(mktemp -d)
d=$tmp/$name
mkdir -p "$d/vsplugin"
install -m 755 integrations/linux/setup.sh "$d/setup.sh"
install -m 755 integrations/linux/install.sh "$d/install.sh"
# optional: the VLC module (PUSHMPC_VLC_PLUGIN=<libpushmpc_plugin.so>) with the clip its installer's hardware-decoding
# self-test plays (PUSHMPC_VLC_SELFTEST_CLIP, vlc-plugin.yml's clips/hwclip.mkv: H.264 640x360, no B-frames; shipped as
# vlc/pushmpc-selftest.mkv next to pushmpc-vlc.sh), and the Kodi add-on folder with its install.sh (PUSHMPC_KODI_DIR),
# which setup.sh installs when VLC / Kodi is found
if [ -n "${PUSHMPC_VLC_PLUGIN:-}" ] && [ -f "$PUSHMPC_VLC_PLUGIN" ]; then
    mkdir -p "$d/vlc"; install -m 755 "$PUSHMPC_VLC_PLUGIN" "$d/vlc/libpushmpc_plugin.so"; install -m 755 vlcplugin/install/pushmpc-vlc.sh "$d/vlc/pushmpc-vlc.sh"
    # PushMPC's OpenGL output with FSR 1 upscaling (vout=pushmpc_gl), from the same build; the installer sets it up
    glf="$(dirname "$PUSHMPC_VLC_PLUGIN")/libpushmpc_gl_plugin.so"
    if [ -f "$glf" ]; then install -m 755 "$glf" "$d/vlc/libpushmpc_gl_plugin.so"; else echo "make-tarball.sh: no libpushmpc_gl_plugin.so next to the VLC module: VLC keeps its own output" >&2; fi
    if [ -n "${PUSHMPC_VLC_SELFTEST_CLIP:-}" ] && [ -f "$PUSHMPC_VLC_SELFTEST_CLIP" ]; then install -m 644 "$PUSHMPC_VLC_SELFTEST_CLIP" "$d/vlc/pushmpc-selftest.mkv"
    else echo "make-tarball.sh: no PUSHMPC_VLC_SELFTEST_CLIP: VLC's hardware-decoding self-test will be skipped on install" >&2; fi
fi
# the pmml runtime's parts setup.sh installs (PushFlow on the GPU for the ml backend): pmml's graphs, generated by
# pmml/scripts/make_graphs.py (PUSHMPC_PMML_GRAPHS), its pinned fetch and the pin file; the plugin must then be built
# with -DPMML_ORT_INCLUDE (the ml backend)
if [ -n "${PUSHMPC_PMML_GRAPHS:-}" ] && [ -f "$PUSHMPC_PMML_GRAPHS/synth-yuv.onnx" ]; then
    mkdir -p "$d/pmml/graphs"; cp "$PUSHMPC_PMML_GRAPHS"/*.onnx "$d/pmml/graphs/"
    install -m 644 pmml/scripts/fetch_runtime.py "$d/pmml/fetch_runtime.py"; install -m 644 scripts/ml-runtime-pin.json "$d/pmml/ml-runtime-pin.json"
    # pmml_cli (PUSHMPC_PMML_CLI): Auto's measurement of every PushFlow candidate on the user's GPU (setup.sh starts it)
    if [ -n "${PUSHMPC_PMML_CLI:-}" ] && [ -f "$PUSHMPC_PMML_CLI" ]; then install -m 755 "$PUSHMPC_PMML_CLI" "$d/pmml/pmml_cli"; fi
    # the anime upscalers: the model graphs (no weights) and the pin setup.sh fetches them by
    if [ -d "$PUSHMPC_PMML_GRAPHS/anime-sr" ]; then mkdir -p "$d/pmml/graphs/anime-sr"; cp "$PUSHMPC_PMML_GRAPHS"/anime-sr/*.onnx "$d/pmml/graphs/anime-sr/"; fi
    install -m 644 scripts/anime-models-pin.json "$d/pmml/anime-models-pin.json"
fi
# optional: PushMPC's native hook for the distro mpv (PUSHMPC_MPVNATIVE_DIR = mpv-native.yml's hook folder:
# pushmpc_hook.so, libpushmpc-avfilter-*.so, libpushmpc_engine.so; the sidecar engines libpushmpc_engine_nvl.so and
# libpushmpc_engine_ml.so with pushmpc-nvvfx-selftest and pmml_cli when the folder has them) with its installer
if [ -n "${PUSHMPC_MPVNATIVE_DIR:-}" ] && [ -f "$PUSHMPC_MPVNATIVE_DIR/pushmpc_hook.so" ]; then
    mkdir -p "$d/mpvnative"; cp "$PUSHMPC_MPVNATIVE_DIR"/*.so "$d/mpvnative/"
    for x in pushmpc-nvvfx-selftest pmml_cli; do [ -f "$PUSHMPC_MPVNATIVE_DIR/$x" ] && install -m 755 "$PUSHMPC_MPVNATIVE_DIR/$x" "$d/mpvnative/$x"; done
    [ -f "$PUSHMPC_MPVNATIVE_DIR/SOURCES.txt" ] && cp "$PUSHMPC_MPVNATIVE_DIR/SOURCES.txt" "$d/mpvnative/"
    install -m 755 mpvnative/install/pushmpc-native.sh "$d/mpvnative/pushmpc-native.sh"
fi
# optional: Plex (Flathub) through LD_PRELOAD (PUSHMPC_PLEX_DIR: pushmpc_preload.so and pushmpc-plex-selftest) with its
# installer and pushmpc-apps-linux.sh (Snap Plex, Flathub Stremio / Jellyfin Desktop, Stremio 4, Emby Theater: it
# takes the hook and the libavfilter builds from mpvnative/); the libavfilter 8 builds and the engine are the native hook's (symlinks into mpvnative/, no second copy)
if [ -n "${PUSHMPC_PLEX_DIR:-}" ] && [ -f "$PUSHMPC_PLEX_DIR/pushmpc_preload.so" ] && [ -f "$d/mpvnative/libpushmpc_engine.so" ] && ls "$d"/mpvnative/libpushmpc-avfilter-8.*.so >/dev/null 2>&1; then
    mkdir -p "$d/plex"; install -m 755 "$PUSHMPC_PLEX_DIR/pushmpc_preload.so" "$d/plex/pushmpc_preload.so"
    if [ -f "$PUSHMPC_PLEX_DIR/pushmpc-plex-selftest" ]; then install -m 755 "$PUSHMPC_PLEX_DIR/pushmpc-plex-selftest" "$d/plex/pushmpc-plex-selftest"; fi
    install -m 755 mpvnative/install/pushmpc-plex-linux.sh "$d/plex/pushmpc-plex-linux.sh"
    install -m 755 mpvnative/install/pushmpc-apps-linux.sh "$d/plex/pushmpc-apps-linux.sh"
    for f in "$d"/mpvnative/libpushmpc-avfilter-8.*.so "$d"/mpvnative/libpushmpc_engine*.so "$d/mpvnative/SOURCES.txt" "$d/mpvnative/pushmpc-nvvfx-selftest" "$d/mpvnative/pmml_cli" "$d/mpvnative/pushmpc_hook.so"; do if [ -f "$f" ]; then ln -s "../mpvnative/$(basename "$f")" "$d/plex/$(basename "$f")"; fi; done
fi
if [ -n "${PUSHMPC_KODI_DIR:-}" ] && [ -f "$PUSHMPC_KODI_DIR/install.sh" ]; then mkdir -p "$d/kodi"; cp -R "$PUSHMPC_KODI_DIR/." "$d/kodi/"; fi
# optional: capture mode (PUSHMPC_CAPTURE_BIN = the pushmpc-capture binary) with its launcher, which setup.sh installs for
# the players PushMPC cannot plug into
if [ -n "${PUSHMPC_CAPTURE_BIN:-}" ] && [ -f "$PUSHMPC_CAPTURE_BIN" ]; then
    mkdir -p "$d/capture"; install -m 755 "$PUSHMPC_CAPTURE_BIN" "$d/capture/pushmpc-capture"; install -m 755 scripts/pushmpc-capture.sh "$d/capture/pushmpc-capture.sh"
fi
install -m 755 integrations/mpv/mpv-integration.sh "$d/mpv-integration.sh"
install -m 755 "$so" "$d/vsplugin/pushmpc_vs.so"
install -m 644 vsplugin/scripts/pushmpc.vpy "$d/vsplugin/pushmpc.vpy"
install -m 644 integrations/mpv/pushmpc.lua "$d/vsplugin/pushmpc.lua"
# the ArtCNN upscaling shaders (generated from the pinned ONNX weights; Python 3, stdlib only)
python3 integrations/mpv/make-shaders.py "$d/vsplugin/shaders"
install -m 644 LICENSE "$d/LICENSE"
# the Linux NVIDIA backend's runtime fetcher (NVIDIA's files are downloaded on the user's machine, never shipped) and
# its self-test (optional 5th argument), when this build has them
[ -f scripts/nvidia-vfx-fetch.sh ] && install -m 755 scripts/nvidia-vfx-fetch.sh "$d/nvidia-vfx-fetch.sh"
[ -f scripts/nvidia-vfx-pin.json ] && install -m 644 scripts/nvidia-vfx-pin.json "$d/nvidia-vfx-pin.json"
[ -n "${5:-}" ] && [ -f "$5" ] && install -m 755 "$5" "$d/vsplugin/pushmpc-nvvfx-selftest"
cat > "$d/README.txt" <<EOF
PushMPC $ver for Linux ($arch): frame generation and the scene-cut guard for mpv and mpv-based players.

Install (for your user only, no administrator password):
    sh setup.sh
Remove:
    sh ~/.local/share/pushmpc/setup.sh uninstall

mpv needs VapourSynth. Arch, Manjaro and EndeavourOS have it; Ubuntu, Debian and Mint build mpv without it, so the
installer offers mpv from Flathub (io.mpv.Mpv, user install) instead. Players set up when found: mpv, mpv from
Flathub, Celluloid, Haruna, SMPlayer, MPC-QT, Jellyfin MPV Shim, Plex-MPV-Shim and Kodi (mpv as its external player).
VLC gets the PushMPC module when this download has it (vlc/). Players PushMPC cannot plug into (Flathub Celluloid,
Stremio, Totem, Clapper, browsers) get capture mode (capture/): a menu entry "<Player> with PushMPC" that shows the
player's picture with smoother motion over its window. setup.sh prints the engine Auto starts with for your
graphics card (sh setup.sh plan). Every change is backed up and undone exactly by the uninstall.

Settings: ~/.config/pushmpc/settings.ini (Smoother=Auto, 2..8 or Off). Logs: ~/.local/state/pushmpc/logs.
https://github.com/CptPakundo/PushMPC
EOF
# reproducible: fixed owner, sorted, the commit time as mtime when available
mt=${SOURCE_DATE_EPOCH:-$(git log -1 --format=%ct 2>/dev/null || date +%s)}
(cd "$tmp" && tar --sort=name --owner=0 --group=0 --numeric-owner --mtime="@$mt" -czf "$out/$name.tar.gz" "$name")
rm -rf "$tmp"
( cd "$out" && sha256sum "$name.tar.gz" > "$name.tar.gz.sha256" )
echo "$out/$name.tar.gz"
