// gpu_bench: quality and speed of the portable engines on real clips (Y4M, 4:2:0, 8 or 10 bits). CI fetches public
// clips (vsplugin-gpu.yml); it also runs on a real GPU. Every number is printed as a Markdown table row
// (| clip | test | method | PSNR-Y | SSIM-Y | ms | note |) and appended to --csv.
//   interp   held-out frames: frame 2i+1 made from frames 2i and 2i+2 at t = 1/2 by each method (the GPU engine with the
//            block matcher at quality 1 and 2, NVIDIA optical flow where the device has it, the CPU engine, a blend,
//            a repeat), scored against the real frame. --y4m-out writes each method's frames and the reference for VMAF.
//   twos     the clip made "on twos" (each even frame shown twice); the duplicate's place, generated by the backend
//            with Dedup and without, against the real odd frame (anime-style motion).
//   upscale  each frame reduced 2x (box filter), upscaled back with FSR1 (EASU + RCAS) at several sharpness values,
//            NIS, bicubic chroma and bilinear (CPU), against the original.
//   cuts     every consecutive pair of the clip, then the junction to --cut-with's first frame: the cut decision
//            (PushFPS's rule, PushMPC's guard) on the junction and the false cuts on the motion pairs.
#include <chrono>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <map>
#include <string>
#include <vector>
#include "gpu_backend.h"
#include "portable_engine.h"

using namespace pmvs;
using namespace pmvs::gpu;

struct Pic {
    int w = 0, h = 0, bits = 8;
    std::vector<uint16_t> p[3];
    int PW(int i) const { return i ? (w + 1) / 2 : w; }
    int PH(int i) const { return i ? (h + 1) / 2 : h; }
    std::vector<uint8_t> bytes[3];
    void Alloc(int W, int H, int B) { w = W; h = H; bits = B; for (int i = 0; i < 3; ++i) p[i].assign(size_t(PW(i)) * size_t(PH(i)), 0); }
    YuvView View()
    {
        YuvView v; v.width = w; v.height = h; v.bits = bits;
        const int bps = bits > 8 ? 2 : 1;
        for (int i = 0; i < 3; ++i) {
            bytes[i].resize(p[i].size() * size_t(bps));
            for (size_t k = 0; k < p[i].size(); ++k) { if (bps == 1) bytes[i][k] = uint8_t(p[i][k]); else std::memcpy(&bytes[i][k * 2], &p[i][k], 2); }
            v.data[i] = bytes[i].data(); v.stride[i] = ptrdiff_t(PW(i)) * bps;
        }
        return v;
    }
    YuvOut Out()
    {
        const int bps = bits > 8 ? 2 : 1;
        YuvOut o;
        for (int i = 0; i < 3; ++i) { bytes[i].assign(p[i].size() * size_t(bps), 0); o.data[i] = bytes[i].data(); o.stride[i] = ptrdiff_t(PW(i)) * bps; }
        return o;
    }
    void FromBytes()
    {
        const int bps = bits > 8 ? 2 : 1;
        for (int i = 0; i < 3; ++i) for (size_t k = 0; k < p[i].size(); ++k) { if (bps == 1) p[i][k] = bytes[i][k]; else std::memcpy(&p[i][k], &bytes[i][k * 2], 2); }
    }
};

// ---- Y4M
struct Y4m { int w = 0, h = 0, bits = 8; std::string header; std::vector<Pic> frames; };
static bool ReadY4m(const std::string& path, int maxFrames, int skip, Y4m& out, std::string& err)
{
    std::ifstream f(path, std::ios::binary);
    if (!f) { err = "cannot open " + path; return false; }
    std::getline(f, out.header);
    if (out.header.rfind("YUV4MPEG2", 0) != 0) { err = path + ": not a Y4M file"; return false; }
    std::string colour = "420";
    size_t pos = 0;
    while ((pos = out.header.find(' ', pos)) != std::string::npos) {
        ++pos;
        const char tag = out.header[pos];
        const std::string val = out.header.substr(pos + 1, out.header.find(' ', pos) - pos - 1);
        if (tag == 'W') out.w = std::atoi(val.c_str());
        else if (tag == 'H') out.h = std::atoi(val.c_str());
        else if (tag == 'C') colour = val;
    }
    if (colour.rfind("420", 0) != 0) { err = path + ": only 4:2:0 (C" + colour + ")"; return false; }
    out.bits = colour.find("p10") != std::string::npos ? 10 : colour.find("p12") != std::string::npos ? 12 : colour.find("p16") != std::string::npos ? 16 : 8;
    const int bps = out.bits > 8 ? 2 : 1;
    std::string line;
    int n = 0;
    while (std::getline(f, line) && line.rfind("FRAME", 0) == 0) {
        Pic p; p.Alloc(out.w, out.h, out.bits);
        bool whole = true;
        for (int i = 0; i < 3 && whole; ++i) {
            std::vector<uint8_t> raw(p.p[i].size() * size_t(bps));
            f.read(reinterpret_cast<char*>(raw.data()), std::streamsize(raw.size()));
            if (!f) { whole = false; break; }   // a truncated last frame (a partial download) ends the clip
            for (size_t k = 0; k < p.p[i].size(); ++k) p.p[i][k] = bps == 1 ? raw[k] : uint16_t(raw[2 * k] | (raw[2 * k + 1] << 8));
        }
        if (!whole) break;
        if (n++ < skip) continue;
        out.frames.push_back(std::move(p));
        if (int(out.frames.size()) >= maxFrames) break;
    }
    if (out.frames.size() < 3) { err = path + ": fewer than 3 frames"; return false; }
    return true;
}
static void WriteY4m(std::ofstream& f, const Pic& p)
{
    f << "FRAME\n";
    for (int i = 0; i < 3; ++i)
        for (uint16_t v : p.p[i]) { if (p.bits > 8) { f.put(char(v & 255)); f.put(char(v >> 8)); } else f.put(char(v)); }
}

// ---- metrics (luma)
static double Psnr(const Pic& a, const Pic& b)
{
    double se = 0;
    for (size_t k = 0; k < a.p[0].size(); ++k) { const double d = double(a.p[0][k]) - double(b.p[0][k]); se += d * d; }
    se /= double(a.p[0].size());
    const double m = double((1 << a.bits) - 1);
    return se <= 1e-12 ? 99.0 : 10 * std::log10(m * m / se);
}
static double Ssim(const Pic& a, const Pic& b)
{
    const double L = double((1 << a.bits) - 1), c1 = (0.01 * L) * (0.01 * L), c2 = (0.03 * L) * (0.03 * L);
    double sum = 0; int n = 0;
    for (int y = 0; y + 8 <= a.h; y += 4)
        for (int x = 0; x + 8 <= a.w; x += 4) {
            double ma = 0, mb = 0, va = 0, vb = 0, cv = 0;
            for (int j = 0; j < 8; ++j) for (int i = 0; i < 8; ++i) { ma += a.p[0][size_t(y + j) * size_t(a.w) + size_t(x + i)]; mb += b.p[0][size_t(y + j) * size_t(b.w) + size_t(x + i)]; }
            ma /= 64; mb /= 64;
            for (int j = 0; j < 8; ++j) for (int i = 0; i < 8; ++i) {
                const double da = a.p[0][size_t(y + j) * size_t(a.w) + size_t(x + i)] - ma, db = b.p[0][size_t(y + j) * size_t(b.w) + size_t(x + i)] - mb;
                va += da * da; vb += db * db; cv += da * db;
            }
            va /= 63; vb /= 63; cv /= 63;
            sum += ((2 * ma * mb + c1) * (2 * cv + c2)) / ((ma * ma + mb * mb + c1) * (va + vb + c2));
            ++n;
        }
    return n ? sum / n : 1.0;
}

static std::string g_clip, g_csv, g_y4mOut, g_device;
static void Row(const std::string& test, const std::string& method, double psnr, double ssim, double ms, const std::string& note = "")
{
    std::printf("| %s | %s | %s | %.2f | %.4f | %.1f | %s |\n", g_clip.c_str(), test.c_str(), method.c_str(), psnr, ssim, ms, note.c_str());
    if (!g_csv.empty()) {
        std::ofstream f(g_csv, std::ios::app);
        f << g_clip << ',' << test << ',' << method << ',' << psnr << ',' << ssim << ',' << ms << ',' << note << '\n';
    }
}
static double Now() { return std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now().time_since_epoch()).count(); }
static bool MakeEngine(Engine& e, const Config& c, std::string& err) { DeviceRequest r; r.device = g_device; r.allowCpu = true; return e.Configure(c, r, err); }

static portable::Picture ToPicture(const Pic& f, int finest)
{
    portable::Picture p;
    for (int i = 0; i < 3; ++i) { p.p[i].w = f.PW(i); p.p[i].h = f.PH(i); p.p[i].px = f.p[i]; }
    veyra::portable::Gray g(f.w, f.h);
    const int shift = f.bits - 8;
    for (size_t k = 0; k < f.p[0].size(); ++k) g.px[k] = uint8_t(shift ? std::min(255, (int(f.p[0][k]) + (1 << (shift - 1))) >> shift) : f.p[0][k]);
    p.pyramid = std::make_shared<const veyra::portable::Pyramid>(veyra::portable::Pyramid::of(std::move(g), 4));
    (void)finest;
    return p;
}

// ---- interp
static void BenchInterp(Y4m& clip)
{
    struct Method { std::string name; int kind; int quality; bool of; };   // kind 0 GPU, 1 CPU, 2 blend, 3 repeat
    std::vector<Method> methods = { { "gpu-blocks-q2", 0, 2, false }, { "gpu-blocks-q1", 0, 1, false }, { "gpu-nvof", 0, 2, true }, { "cpu", 1, 1, false }, { "blend", 2, 0, false }, { "repeat", 3, 0, false } };
    std::ofstream ref;
    if (!g_y4mOut.empty()) {
        ref.open(g_y4mOut + "/" + g_clip + "_ref.y4m", std::ios::binary);
        ref << clip.header << '\n';
        for (size_t i = 1; i + 1 < clip.frames.size(); i += 2) WriteY4m(ref, clip.frames[i]);
    }
    for (const Method& m : methods) {
        Engine e;
        std::string err;
        if (m.kind == 0) {
            Config c; c.width = clip.w; c.height = clip.h; c.bits = clip.bits; c.quality = m.quality; c.blockMatcherOnly = !m.of;
            if (!MakeEngine(e, c, err)) { std::printf("| %s | interp | %s | - | - | - | %s |\n", g_clip.c_str(), m.name.c_str(), err.c_str()); continue; }
            if (m.of && !e.OpticalFlowActive()) { std::printf("| %s | interp | %s | - | - | - | no VK_NV_optical_flow on this device |\n", g_clip.c_str(), m.name.c_str()); continue; }
        }
        std::ofstream y4m;
        if (!g_y4mOut.empty()) { y4m.open(g_y4mOut + "/" + g_clip + "_" + m.name + ".y4m", std::ios::binary); y4m << clip.header << '\n'; }
        double ps = 0, ss = 0, ms = 0; int n = 0, cuts = 0;
        int prevPair = -1, prevSlotA = -1;
        int slotPrev = -1;
        veyra::portable::MotionField lastF, lastK;
        for (size_t i = 0; i + 2 < clip.frames.size(); i += 2) {
            Pic& a = clip.frames[i]; Pic& b = clip.frames[i + 2];
            Pic g; g.Alloc(clip.w, clip.h, clip.bits);
            const double t0 = Now();
            if (m.kind == 0) {
                const int sa = slotPrev >= 0 ? slotPrev : e.Upload(a.View(), err);
                const int sb = e.Upload(b.View(), err);
                PairStats st;
                const int pr = e.Estimate(sa, sb, prevPair, st, err);
                if (pr < 0) { std::printf("estimate: %s\n", err.c_str()); break; }
                cuts += st.cutRule ? 1 : 0;
                YuvOut o = g.Out();
                int out = -1; uint64_t ticket = 0;
                if (!e.Generate(pr, 0.5f, st.cutRule ? 1 : 0, out, ticket, err) || !e.Wait(ticket, err)) { std::printf("generate: %s\n", err.c_str()); break; }
                e.Read(out, o);
                g.FromBytes();
                if (prevPair >= 0) e.ReleasePair(prevPair);
                if (prevSlotA >= 0) e.ReleaseSlot(prevSlotA);
                prevPair = pr; prevSlotA = sa; slotPrev = sb;
            } else if (m.kind == 1) {
                const portable::Picture pa = ToPicture(a, 1), pb = ToPicture(b, 1);
                veyra::portable::MotionSettings mset; mset.finestLevel = 1;
                const veyra::portable::MotionEstimator est(mset);
                const auto f = est.estimate(*pa.pyramid, *pb.pyramid, lastF.empty() ? nullptr : &lastF), k = est.estimate(*pb.pyramid, *pa.pyramid, lastK.empty() ? nullptr : &lastK);
                lastF = f; lastK = k;
                cuts += f.sceneCut || k.sceneCut ? 1 : 0;
                portable::Picture r;
                portable::InterpolatePlanes(pa, pb, f, k, 0.5f, (1 << clip.bits) - 1, r, 0);
                for (int p = 0; p < 3; ++p) g.p[p] = r.p[p].px;
            } else if (m.kind == 2) {
                for (int p = 0; p < 3; ++p) for (size_t q = 0; q < g.p[p].size(); ++q) g.p[p][q] = uint16_t((a.p[p][q] + b.p[p][q] + 1) / 2);
            } else {
                for (int p = 0; p < 3; ++p) g.p[p] = a.p[p];
            }
            ms += Now() - t0;
            ps += Psnr(g, clip.frames[i + 1]); ss += Ssim(g, clip.frames[i + 1]); ++n;
            if (y4m) WriteY4m(y4m, g);
        }
        if (n) Row("interp", m.name, ps / n, ss / n, ms / n, cuts ? std::to_string(cuts) + " pairs held as cuts" : "");
    }
}

// ---- twos: the backend on int handles, with and without Dedup
static void BenchTwos(Y4m& clip)
{
    const int K = 2;
    std::vector<Pic> src;
    for (size_t j = 0; j < clip.frames.size(); ++j) src.push_back(clip.frames[j & ~size_t(1)]);
    for (int dedup = 1; dedup >= 0; --dedup) {
        Pipeline<int> pipe;
        GpuBackend<int> be;
        std::map<int, Pic> outs;
        int next = 1;
        Config c; c.width = clip.w; c.height = clip.h; c.bits = clip.bits;
        std::string err;
        if (!MakeEngine(be.engine, c, err)) { std::printf("twos: %s\n", err.c_str()); return; }
        be.dedup = dedup != 0; be.subtitleHold = false;
        be.cadence.Configure(K, dedup ? 2 : 0, int64_t(src.size()));
        pipe.Init(K, int64_t(src.size()), SrcDur100ns(24000, 1001));
        pipe.SetLookahead(be.Lookahead());
        pipe.Reset();
        be.grid = pipe.GridOf();
        be.source = [&](int64_t s, YuvView& v, void*& keep) { if (s < 0 || s >= int64_t(src.size())) return false; v = src[size_t(s)].View(); keep = nullptr; return true; };
        be.unkeep = [](void*) {};
        be.alloc = [&](YuvOut& o, int& f, void*) { f = next++; Pic& p = outs[f]; p.Alloc(clip.w, clip.h, clip.bits); o = p.Out(); return true; };
        be.release = [&](int f) { outs.erase(f); };
        double ps = 0, ss = 0; int n = 0;
        const double t0 = Now();
        for (size_t j = 1; j + 3 < src.size(); j += 2) {
            const int64_t outN = int64_t(j) * K;
            int64_t from, to;
            pipe.Requests(outN, from, to);
            auto r = pipe.Produce(outN, from, be, 10000);
            if (!r.ok) { std::printf("twos: %s\n", r.err.c_str()); break; }
            Pic& g = outs[r.frame];
            g.FromBytes();
            ps += Psnr(g, clip.frames[j]); ss += Ssim(g, clip.frames[j]); ++n;
        }
        if (n) Row("twos", dedup ? "gpu-dedup" : "gpu-no-dedup", ps / n, ss / n, (Now() - t0) / n, dedup ? std::to_string(be.stats.duplicates) + " duplicates found" : "");
    }
}

// ---- upscale
static void Reduce(const Pic& big, Pic& s)
{
    s.Alloc(big.w / 2 & ~1, big.h / 2 & ~1, big.bits);
    for (int i = 0; i < 3; ++i)
        for (int y = 0; y < s.PH(i); ++y)
            for (int x = 0; x < s.PW(i); ++x) {
                int v = 0;
                for (int dy = 0; dy < 2; ++dy) for (int dx = 0; dx < 2; ++dx) v += big.p[i][size_t(std::min(2 * y + dy, big.PH(i) - 1)) * size_t(big.PW(i)) + size_t(std::min(2 * x + dx, big.PW(i) - 1))];
                s.p[i][size_t(y) * size_t(s.PW(i)) + size_t(x)] = uint16_t((v + 2) / 4);
            }
}
static void BenchUpscale(Y4m& clip, int frames)
{
    struct M { std::string name; Upscaler u; float sharp; };
    const std::vector<M> ms = { { "fsr1-s0.25", Upscaler::Fsr, 0.25f }, { "fsr1-s0.5", Upscaler::Fsr, 0.5f }, { "fsr1-s0.75", Upscaler::Fsr, 0.75f }, { "fsr1-s1.0", Upscaler::Fsr, 1.0f },
                                { "nis-s0.0", Upscaler::Nis, 0.0f }, { "nis-s0.1", Upscaler::Nis, 0.1f }, { "nis-s0.25", Upscaler::Nis, 0.25f }, { "nis-s0.5", Upscaler::Nis, 0.5f } };
    const int W = clip.w & ~3, H = clip.h & ~3;
    std::vector<Pic> big, small;
    for (int f = 0; f < std::min(frames, int(clip.frames.size())); ++f) {
        Pic b; b.Alloc(W, H, clip.bits);
        for (int i = 0; i < 3; ++i) for (int y = 0; y < b.PH(i); ++y) for (int x = 0; x < b.PW(i); ++x) b.p[i][size_t(y) * size_t(b.PW(i)) + size_t(x)] = clip.frames[size_t(f)].p[i][size_t(y) * size_t(clip.frames[size_t(f)].PW(i)) + size_t(x)];
        Pic s; Reduce(b, s);
        big.push_back(b); small.push_back(s);
    }
    for (const M& m : ms) {
        Config c; c.width = small[0].w; c.height = small[0].h; c.bits = clip.bits; c.outWidth = W; c.outHeight = H; c.upscaler = m.u; c.sharpness = m.sharp;
        Engine e;
        std::string err;
        if (!MakeEngine(e, c, err)) { std::printf("upscale: %s\n", err.c_str()); return; }
        double ps = 0, ss = 0, t = 0;
        for (size_t f = 0; f < big.size(); ++f) {
            const double t0 = Now();
            const int s = e.Upload(small[f].View(), err);
            Pic up; up.Alloc(W, H, clip.bits);
            YuvOut o = up.Out();
            int out = -1; uint64_t ticket = 0;
            if (s < 0 || !e.Real(s, out, ticket, err) || !e.Wait(ticket, err)) { std::printf("upscale: %s\n", err.c_str()); return; }
            e.Read(out, o);
            e.ReleaseSlot(s);
            t += Now() - t0;
            up.FromBytes();
            ps += Psnr(up, big[f]); ss += Ssim(up, big[f]);
        }
        Row("upscale-2x", m.name, ps / double(big.size()), ss / double(big.size()), t / double(big.size()));
    }
    // bilinear (CPU), the reference point
    double ps = 0, ss = 0;
    for (size_t f = 0; f < big.size(); ++f) {
        Pic up; up.Alloc(W, H, clip.bits);
        const Pic& s = small[f];
        for (int y = 0; y < H; ++y)
            for (int x = 0; x < W; ++x) {
                const double sx = std::clamp((x + 0.5) * 0.5 - 0.5, 0.0, double(s.w - 1)), sy = std::clamp((y + 0.5) * 0.5 - 0.5, 0.0, double(s.h - 1));
                const int x0 = int(sx), y0 = int(sy), x1 = std::min(x0 + 1, s.w - 1), y1 = std::min(y0 + 1, s.h - 1);
                const double fx = sx - x0, fy = sy - y0;
                auto at = [&](int xx, int yy) { return double(s.p[0][size_t(yy) * size_t(s.w) + size_t(xx)]); };
                up.p[0][size_t(y) * size_t(W) + size_t(x)] = uint16_t(std::lround((at(x0, y0) * (1 - fx) + at(x1, y0) * fx) * (1 - fy) + (at(x0, y1) * (1 - fx) + at(x1, y1) * fx) * fy));
            }
        ps += Psnr(up, big[f]); ss += Ssim(up, big[f]);
    }
    Row("upscale-2x", "bilinear", ps / double(big.size()), ss / double(big.size()), 0);
}

// ---- cuts
static void BenchCuts(Y4m& clip, Y4m* other)
{
    for (int useOf = 0; useOf <= 1; ++useOf) {
        Config c; c.width = clip.w; c.height = clip.h; c.bits = clip.bits; c.blockMatcherOnly = !useOf;
        Engine e;
        std::string err;
        if (!MakeEngine(e, c, err)) { std::printf("cuts: %s\n", err.c_str()); return; }
        if (useOf && !e.OpticalFlowActive()) return;
        CutGuard guard;
        int falseRule = 0, falseGuard = 0, pairs = 0;
        double sumCons = 0;
        int prev = -1, slotA = e.Upload(clip.frames[0].View(), err);
        for (size_t i = 1; i < clip.frames.size(); ++i) {
            const int sb = e.Upload(clip.frames[i].View(), err);
            PairStats st;
            const int p = e.Estimate(slotA, sb, prev, st, err);
            if (p < 0) { std::printf("cuts: %s\n", err.c_str()); return; }
            std::printf("STAT %s %s pair %zu unexpl %.3f %.3f cost %.2f %.2f zero %.2f agree %.3f moving %.3f rule %d
", g_clip.c_str(), useOf ? "nvof" : "blocks", i, st.unexplainedF, st.unexplainedB, st.meanCostF, st.meanCostB, st.zeroCost, st.consistent, st.moving, st.cutRule ? 1 : 0);
            const int d = guard.Decide(st);
            falseRule += d == 1 ? 1 : 0; falseGuard += d == 2 ? 1 : 0; ++pairs; sumCons += st.consistent;
            if (prev >= 0) e.ReleasePair(prev);
            e.ReleaseSlot(slotA);
            prev = p; slotA = sb;
        }
        std::string note = std::to_string(falseRule) + " false cuts by the rule, " + std::to_string(falseGuard) + " by the guard in " + std::to_string(pairs) + " pairs; agreement "
                         + std::to_string(int(100 * sumCons / std::max(1, pairs))) + " %";
        if (other && other->w == clip.w && other->h == clip.h && other->bits == clip.bits) {
            const int sb = e.Upload(other->frames[0].View(), err);
            PairStats st;
            const int p = e.Estimate(slotA, sb, prev, st, err);
            std::printf("STAT %s %s junction unexpl %.3f %.3f cost %.2f %.2f zero %.2f agree %.3f moving %.3f rule %d
", g_clip.c_str(), useOf ? "nvof" : "blocks", st.unexplainedF, st.unexplainedB, st.meanCostF, st.meanCostB, st.zeroCost, st.consistent, st.moving, st.cutRule ? 1 : 0);
            const int d = p >= 0 ? guard.Decide(st) : -1;
            note += std::string("; junction: ") + (d == 1 ? "cut (rule)" : d == 2 ? "cut (guard)" : "MISSED") + " (unexplained " + std::to_string(int(100 * std::max(st.unexplainedF, st.unexplainedB))) + " %)";
        }
        Row("cuts", useOf ? "gpu-nvof" : "gpu-blocks", 0, 0, 0, note);
    }
}

// a synthetic clip with known in-between frames: a detailed procedural picture under a camera that pans, zooms and
// rotates, and a textured disc crossing it the other way (occlusions); 4:2:0 8-bit. For runs where no public clip may
// be fetched (a local GPU), and as a motion type the derf clips lack (zoom + rotation).
static double Hash01(int x, int y) { uint32_t h = uint32_t(x) * 73856093u ^ uint32_t(y) * 19349663u; h ^= h >> 13; h *= 0x5bd1e995u; h ^= h >> 15; return double(h % 1000) / 999.0; }
static double Detail(double x, double y)
{
    const double cx = std::floor(x / 5.0), cy = std::floor(y / 5.0), fx = x / 5.0 - cx, fy = y / 5.0 - cy;
    const double n = (Hash01(int(cx), int(cy)) * (1 - fx) + Hash01(int(cx) + 1, int(cy)) * fx) * (1 - fy) + (Hash01(int(cx), int(cy) + 1) * (1 - fx) + Hash01(int(cx) + 1, int(cy) + 1) * fx) * fy;
    return 40 + 120 * n + 50 * std::sin(x * 0.045) * std::cos(y * 0.037) + 30 * ((int(std::floor(x / 40)) + int(std::floor(y / 40))) & 1);
}
static void Synthetic(int W, int H, int frames, Y4m& out)
{
    out.w = W; out.h = H; out.bits = 8;
    out.header = "YUV4MPEG2 W" + std::to_string(W) + " H" + std::to_string(H) + " F50:1 Ip A1:1 C420jpeg";
    for (int f = 0; f < frames; ++f) {
        const double t = f;
        const double s = 1.0 + 0.004 * t, a = 0.0025 * t, px = 3.0 * t, py = 1.2 * t;
        const double dx = W * 0.75 - 9.0 * t, dy = H * 0.5 + 2.0 * t, r = H * 0.18;
        Pic p; p.Alloc(W, H, 8);
        auto sample = [&](double x, double y, int plane) {
            const double ox = x - dx, oy = y - dy;
            if (ox * ox + oy * oy < r * r) return plane == 0 ? 200 - 0.6 * Detail(ox * 1.7 + 500, oy * 1.7) : 128 + (plane == 1 ? 30.0 : -25.0);
            const double cx = x - W / 2.0, cy = y - H / 2.0;
            const double u = (std::cos(a) * cx - std::sin(a) * cy) / s + W / 2.0 + px, v = (std::sin(a) * cx + std::cos(a) * cy) / s + H / 2.0 + py;
            return plane == 0 ? Detail(u, v) : 128 + (plane == 1 ? 12 : -10) * std::sin(u * 0.02 + v * 0.013);
        };
        for (int i = 0; i < 3; ++i)
            for (int y = 0; y < p.PH(i); ++y)
                for (int x = 0; x < p.PW(i); ++x) {
                    const double sx = i ? 2 * x + 1.0 : x + 0.5, sy = i ? 2 * y + 1.0 : y + 0.5;
                    p.p[i][size_t(y) * size_t(p.PW(i)) + size_t(x)] = uint16_t(std::clamp(std::lround(sample(sx, sy, i)), 0L, 255L));
                }
        out.frames.push_back(std::move(p));
    }
}

int main(int argc, char** argv)
{
    std::string file, test = "interp", cutWith;
    int frames = 40, skip = 0;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        auto next = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
        if (a == "--clip") g_clip = next();
        else if (a == "--test") test = next();
        else if (a == "--frames") frames = std::atoi(next().c_str());
        else if (a == "--skip") skip = std::atoi(next().c_str());
        else if (a == "--csv") g_csv = next();
        else if (a == "--y4m-out") g_y4mOut = next();
        else if (a == "--device") g_device = next();
        else if (a == "--cut-with") cutWith = next();
        else file = a;
    }
    if (file.empty()) { std::printf("usage: gpu_bench clip.y4m [--clip name] [--test interp|twos|upscale|cuts] [--frames N] [--skip N] [--csv f] [--y4m-out dir] [--cut-with other.y4m] [--device d]\n"); return 2; }
    if (g_clip.empty()) g_clip = file.substr(file.find_last_of("/\\") + 1);
    Y4m clip;
    std::string err;
    if (file == "synthetic") Synthetic(1280, 720, frames, clip);
    else if (!ReadY4m(file, frames, skip, clip, err)) { std::printf("gpu_bench: %s\n", err.c_str()); return 1; }
    std::printf("gpu_bench: %s, %dx%d %d-bit, %zu frames, test %s\n", g_clip.c_str(), clip.w, clip.h, clip.bits, clip.frames.size(), test.c_str());
    if (test == "interp") BenchInterp(clip);
    else if (test == "twos") BenchTwos(clip);
    else if (test == "upscale") BenchUpscale(clip, std::min(frames, 8));
    else if (test == "cuts") {
        Y4m other;
        Y4m* o = nullptr;
        if (!cutWith.empty() && ReadY4m(cutWith, 3, 0, other, err)) o = &other;
        BenchCuts(clip, o);
    }
    return 0;
}
