#!/bin/sh
# make-cuda-stub.sh <runtime-dir> <out-dir>: a stub libcuda.so.1 for hosted CI runners (no NVIDIA driver): every CUDA
# driver entry point that the Video Effects runtime's libraries import (nm), plus the ones the backend's loader binds,
# each answering CUDA_ERROR_NO_DEVICE (100). Put <out-dir> first on LD_LIBRARY_PATH; nvl_struct_test then loads the
# real runtime libraries with all their symbols resolved.
set -eu
rt=$1; out=$2
mkdir -p "$out"
syms=$( (find "$rt" -name '*.so*' -type f -exec nm -D --undefined-only {} + 2>/dev/null | awk '{print $NF}' | sed 's/@.*//' | grep -E '^cu[A-Z]';
         grep -ohE '"cu[A-Za-z0-9_]+"' "$(dirname "$0")/../../engines/nvidia-linux/nvl_loader.cpp" | tr -d '"') | sort -u)
{
    echo "/* generated by make-cuda-stub.sh: CUDA_ERROR_NO_DEVICE everywhere */"
    for s in $syms; do echo "int $s(void) { return 100; }"; done
} > "$out/cuda_stub.c"
cc -shared -fPIC -o "$out/libcuda.so.1" -Wl,-soname,libcuda.so.1 "$out/cuda_stub.c"
ln -sf libcuda.so.1 "$out/libcuda.so"
echo "stub libcuda.so.1: $(echo "$syms" | wc -l) entry points"
